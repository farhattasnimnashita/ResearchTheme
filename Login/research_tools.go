func migrateResearchTools(db *Database) error {
	idType := "INTEGER PRIMARY KEY"
	if db.postgres {
		idType = "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
	}
	queries := []string{
		`CREATE TABLE IF NOT EXISTS research_tool_records (
			id ` + idType + `,
			project_id BIGINT NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
			feature_key TEXT NOT NULL,
			title TEXT NOT NULL,
			fields_json TEXT NOT NULL,
			created_by BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
			created_at BIGINT NOT NULL,
			updated_at BIGINT NOT NULL
		)`,
		`CREATE INDEX IF NOT EXISTS idx_research_tool_project_feature
			ON research_tool_records(project_id, feature_key, updated_at)`,
	}
	for _, query := range queries {
		if _, err := db.Exec(query); err != nil {
			return err
		}
	}
	return nil
}

func validResearchToolFeature(feature string) bool {
	_, ok := researchToolDefinitions[feature]
	return ok
}

func (a *App) researchToolCitationSources(w http.ResponseWriter, r *http.Request) {
	u, err := a.user(r)
	if err != nil {
		fail(w, http.StatusUnauthorized, "Please log in.")
		return
	}
	if u.Role != "student" && u.Role != "teacher" {
		fail(w, http.StatusForbidden, "You cannot access project citation sources.")
		return
	}
	projectID, err := strconv.ParseInt(r.URL.Query().Get("project_id"), 10, 64)
	if err != nil || projectID <= 0 || !a.projectAccess(u, projectID) {
		fail(w, http.StatusForbidden, "Choose a project you can access.")
		return
	}
	rows, err := a.db.Query(`
		SELECT id,title,authors,publication_year,venue,doi,paper_url,objective,methodology,
		       dataset,key_findings,limitations,research_gap,relevance,created_at
		FROM literature_papers
		WHERE student_id IN (
			SELECT student_id FROM projects WHERE id=?
			UNION
			SELECT user_id FROM team_members WHERE project_id=?
		)
		ORDER BY created_at DESC,id DESC
	`, projectID, projectID)
	if err != nil {
		fail(w, http.StatusInternalServerError, "Could not load the team's literature sources.")
		return
	}
	defer rows.Close()
	papers := make([]literaturePaper, 0)
	for rows.Next() {
		var paper literaturePaper
		if err := rows.Scan(&paper.ID, &paper.Title, &paper.Authors, &paper.Year, &paper.Venue, &paper.DOI, &paper.PaperURL, &paper.Objective, &paper.Methodology, &paper.Dataset, &paper.KeyFindings, &paper.Limitations, &paper.ResearchGap, &paper.Relevance, &paper.CreatedAt); err != nil {
			fail(w, http.StatusInternalServerError, "Could not read the team's literature sources.")
			return
		}
		papers = append(papers, paper)
	}
	if rows.Err() != nil {
		fail(w, http.StatusInternalServerError, "Could not read the team's literature sources.")
		return
	}
	reply(w, http.StatusOK, papers)
}

func (a *App) researchToolRecords(w http.ResponseWriter, r *http.Request) {
	u, err := a.user(r)
	if err != nil {
		fail(w, http.StatusUnauthorized, "Please log in.")
		return
	}
	if u.Role != "student" && u.Role != "teacher" {
		fail(w, http.StatusForbidden, "You cannot access project research tools.")
		return
	}
	feature := r.PathValue("feature")
	if !validResearchToolFeature(feature) {
		fail(w, http.StatusNotFound, "Research tool not found.")
		return
	}
	switch r.Method {
	case http.MethodGet:
		pid, parseErr := strconv.ParseInt(r.URL.Query().Get("project_id"), 10, 64)
		if parseErr != nil || pid <= 0 || !a.projectAccess(u, pid) {
			fail(w, http.StatusForbidden, "Choose a project you can access.")
			return
		}
		a.listResearchToolRecords(w, pid, feature)
	case http.MethodPost, http.MethodPut:
		a.saveResearchToolRecord(w, r, u, feature)
	case http.MethodDelete:
		a.deleteResearchToolRecord(w, r, u, feature)
	default:
		w.Header().Set("Allow", "GET, POST, PUT, DELETE")
		fail(w, http.StatusMethodNotAllowed, "Method not allowed.")
	}
}

func (a *App) listResearchToolRecords(w http.ResponseWriter, projectID int64, feature string) {
	rows, err := a.db.Query(`
		SELECT id, project_id, feature_key, title, fields_json, created_by, created_at, updated_at
		FROM research_tool_records
		WHERE project_id=? AND feature_key=?
		ORDER BY updated_at DESC, id DESC
	`, projectID, feature)
	if err != nil {
		fail(w, 500, "Could not load research tool records.")
		return
	}
	defer rows.Close()
	out := make([]researchToolRecord, 0)
	for rows.Next() {
		var item researchToolRecord
		var raw string
		if err := rows.Scan(&item.ID, &item.ProjectID, &item.Feature, &item.Title, &raw, &item.CreatedBy, &item.CreatedAt, &item.UpdatedAt); err != nil {
			fail(w, 500, "Could not read research tool records.")
			return
		}
		item.Fields = map[string]string{}
		if json.Unmarshal([]byte(raw), &item.Fields) != nil {
			fail(w, 500, "A saved research record is invalid.")
			return
		}
		out = append(out, item)
	}
	if rows.Err() != nil {
		fail(w, 500, "Could not read research tool records.")
		return
	}
	reply(w, 200, out)
}

func (a *App) saveResearchToolRecord(w http.ResponseWriter, r *http.Request, u User, feature string) {
	var in struct {
		ID        int64             `json:"id"`
		ProjectID int64             `json:"project_id"`
		Fields    map[string]string `json:"fields"`
	}
	if !decode(w, r, &in) {
		return
	}
	if in.ProjectID <= 0 || !a.projectAccess(u, in.ProjectID) {
		fail(w, 403, "This project is not assigned to you.")
		return
	}
	if in.Fields == nil || len(in.Fields) == 0 || len(in.Fields) > 30 {
		fail(w, 400, "Please complete the research record.")
		return
	}
	for key, value := range in.Fields {
		if !researchToolDefinitions[feature].allowed[key] {
			fail(w, 400, "This field is not part of the selected research tool.")
			return
		}
		value = strings.TrimSpace(value)
		if len(value) > 8000 {
			fail(w, 400, "A field is too long (maximum 8,000 characters).")
			return
		}
		in.Fields[key] = value
	}
	definition := researchToolDefinitions[feature]
	for _, key := range definition.required {
		if strings.TrimSpace(in.Fields[key]) == "" {
			fail(w, 400, "Please complete all required fields.")
			return
		}
	}
	if err := validateResearchToolFields(feature, in.Fields); err != nil {
		fail(w, 400, err.Error())
		return
	}

	if feature == "risk-decision-log" {
		if in.Fields["entry_type"] == "Risk" && (in.Fields["likelihood"] == "" || in.Fields["impact"] == "") {
			fail(w, 400, "Add the likelihood and impact for a risk entry.")
			return
		}
		if in.Fields["entry_type"] == "Decision" && strings.TrimSpace(in.Fields["decision_rationale"]) == "" {
			fail(w, 400, "Add the rationale for this decision.")
			return
		}
	}
	if feature == "research-question-map" {
		questionType := in.Fields["question_type"]
		parent := strings.TrimSpace(in.Fields["parent_question"])
		if questionType == "Sub-question" && parent == "" {
			fail(w, 400, "Choose the main question that this sub-question belongs to.")
			return
		}
		if questionType == "Main question" && parent != "" {
			fail(w, 400, "A main question cannot have a parent question.")
			return
		}
		if linkedGap := strings.TrimSpace(in.Fields["linked_gap"]); linkedGap != "" {
			gapID, parseErr := strconv.ParseInt(linkedGap, 10, 64)
			var count int
			if parseErr != nil || a.db.QueryRow("SELECT COUNT(*) FROM research_tool_records WHERE id=? AND project_id=? AND feature_key='research-gap-tracker'", gapID, in.ProjectID).Scan(&count) != nil || count != 1 {
				fail(w, 400, "Choose a research gap saved in this project.")
				return
			}
		}
		if parent != "" {
			parentID, parseErr := strconv.ParseInt(parent, 10, 64)
			var parentRaw string
			queryErr := a.db.QueryRow("SELECT fields_json FROM research_tool_records WHERE id=? AND project_id=? AND feature_key='research-question-map'", parentID, in.ProjectID).Scan(&parentRaw)
			parentFields := map[string]string{}
			if parseErr != nil || parentID == in.ID || queryErr != nil || json.Unmarshal([]byte(parentRaw), &parentFields) != nil || parentFields["question_type"] != "Main question" {
				fail(w, 400, "Choose a different main question saved in this project.")
				return
			}
			if !a.researchQuestionParentIsAcyclic(in.ProjectID, in.ID, parentID) {
				fail(w, 400, "This parent would create a circular research-question relationship.")
				return
			}
		}
	}
	if feature == "task-dependencies" {
		taskID, _ := strconv.ParseInt(in.Fields["task_id"], 10, 64)
		dependsOnID, _ := strconv.ParseInt(in.Fields["depends_on_id"], 10, 64)
		if err := a.validateTaskDependencyGraph(in.ProjectID, in.ID, taskID, dependsOnID); err != nil {
			fail(w, 400, err.Error())
			return
		}
	}

	if feature == "citation-manager" || feature == "authorship-agreement" {
		field := "paper_id"
		value := in.Fields["paper_id"]
		if feature == "authorship-agreement" {
			field = "member_id"
			value = in.Fields["member_id"]
		}
		duplicate, checkErr := a.researchToolFieldExists(in.ProjectID, feature, field, value, in.ID)
		if checkErr != nil {
			fail(w, 500, "Could not check for an existing record.")
			return
		}
		if duplicate {
			fail(w, 409, "This source or contributor already has a record in this project. Edit the existing record instead of creating a duplicate.")
			return
		}
	}

	title, err := a.researchToolTitle(feature, in.ProjectID, u, in.Fields)
	if err != nil {
		fail(w, 400, err.Error())
		return
	}
	if title == "" || len(title) > 500 {
		fail(w, 400, "A valid record title is required.")
		return
	}
	if feature == "authorship-agreement" && strings.EqualFold(in.Fields["agreement_status"], "Agreed") {
		memberID, _ := strconv.ParseInt(in.Fields["member_id"], 10, 64)
		if memberID != u.ID {
			fail(w, 403, "Only the named contributor can mark their own contribution as agreed.")
			return
		}
	}

	encoded, err := json.Marshal(in.Fields)
	if err != nil {
		fail(w, 400, "Could not read the research record.")
		return
	}
	now := time.Now().Unix()
	if in.ID > 0 {
		var currentProject int64
		var currentFeature string
		if err := a.db.QueryRow("SELECT project_id, feature_key FROM research_tool_records WHERE id=?", in.ID).Scan(&currentProject, &currentFeature); err != nil || currentProject != in.ProjectID || currentFeature != feature {
			fail(w, 404, "Research record not found in this project.")
			return
		}
		_, err = a.db.Exec(`UPDATE research_tool_records SET title=?, fields_json=?, updated_at=? WHERE id=? AND project_id=? AND feature_key=?`, title, string(encoded), now, in.ID, in.ProjectID, feature)
		if err != nil {
			fail(w, 500, "Could not update the research record.")
			return
		}
		reply(w, 200, map[string]any{"id": in.ID, "message": "Research record updated."})
		return
	}
	id, err := a.db.InsertID(`INSERT INTO research_tool_records(project_id, feature_key, title, fields_json, created_by, created_at, updated_at) VALUES(?,?,?,?,?,?,?)`, in.ProjectID, feature, title, string(encoded), u.ID, now, now)
	if err != nil {
		fail(w, 500, "Could not save the research record.")
		return
	}
	reply(w, 201, map[string]any{"id": id, "message": "Research record saved."})
}

func validateResearchToolFields(feature string, fields map[string]string) error {
	choices := map[string]map[string][]string{
		"citation-manager":      {"source_type": {"Journal article", "Conference paper", "Book", "Book chapter", "Thesis", "Dataset", "Website", "Preprint", "Other"}, "citation_style": {"IEEE", "APA 7", "ACM", "Chicago", "Harvard", "Other"}},
		"risk-decision-log":     {"entry_type": {"Risk", "Decision"}, "likelihood": {"Low", "Medium", "High", "Not applicable"}, "impact": {"Low", "Medium", "High", "Critical", "Not applicable"}, "status": {"Open", "Monitoring", "Mitigated", "Decided", "Closed"}},
		"research-gap-tracker":  {"importance": {"Low", "Medium", "High"}, "feasibility": {"Low", "Medium", "High", "Needs assessment"}, "status": {"New", "Under discussion", "Selected", "In progress", "Addressed", "Not proceeding"}},
		"research-question-map": {"question_type": {"Main question", "Sub-question", "Exploratory question"}, "status": {"Draft", "Discussing", "Approved by team", "In progress", "Answered", "Revised"}},
		"dataset-registry":      {"sensitivity": {"Public", "Internal", "Confidential", "Sensitive"}},
		"task-dependencies":     {"dependency_type": {"Finish-to-start", "Start-to-start", "Finish-to-finish", "Informational only"}},
		"authorship-agreement":  {"agreement_status": {"Not discussed", "Proposed", "Agreed", "Needs discussion", "Disputed"}},
		"research-budget":       {"category": {"Equipment", "Software / cloud", "Travel", "Printing / publication", "Data collection", "Other"}, "currency": {"BDT", "USD", "EUR", "GBP", "Other"}, "approval_status": {"Not requested", "Pending", "Approved", "Rejected", "Paid / purchased"}},
		"project-export":        {"export_format": {"ZIP metadata bundle"}, "handover_status": {"Planned", "Preparing", "Ready for review", "Transferred", "Archived"}},
		"data-access-settings":  {"classification": {"Public", "Team only", "Restricted", "Confidential"}, "policy_status": {"Draft", "Pending approval", "Active", "Expired", "Revoked"}},
		"research-impact":       {"output_type": {"Journal paper", "Conference paper", "Dataset", "Software", "Thesis", "Poster", "Other"}},
	}
	for key, allowed := range choices[feature] {
		value := strings.TrimSpace(fields[key])
		if value == "" {
			continue
		}
		valid := false
		for _, option := range allowed {
			if value == option {
				valid = true
				break
			}
		}
		if !valid {
			return fmt.Errorf("choose a valid value for %s", strings.ReplaceAll(key, "_", " "))
		}
	}
	dateKeys := []string{"accessed_date", "review_date", "retention_date", "expense_date", "handover_date", "embargo_start", "embargo_end", "publication_date", "verified_date"}
	for _, key := range dateKeys {
		if value := fields[key]; value != "" {
			if !validTrackingDate(value, false) {
				return fmt.Errorf("%s must be a valid date", strings.ReplaceAll(key, "_", " "))
			}
		}
	}
	urlKeys := []string{"source_url", "receipt_link", "doi_url", "impact_evidence"}
	for _, key := range urlKeys {
		if value := strings.TrimSpace(fields[key]); value != "" {
			if key == "doi_url" && validDOI(value) {
				continue
			}
			if !validResearchToolURL(value) {
				if key == "doi_url" {
					return fmt.Errorf("DOI / official URL must be a DOI or http/https link")
				}
				return fmt.Errorf("%s must be an http or https link", strings.ReplaceAll(key, "_", " "))
			}
		}
	}
	if feature == "research-budget" {
		if _, err := strconv.ParseFloat(fields["quantity"], 64); err != nil || !nonNegativeNumber(fields["quantity"]) {
			return fmt.Errorf("quantity must be zero or a positive number")
		}
		for _, key := range []string{"estimated_cost", "actual_cost"} {
			if fields[key] != "" && !nonNegativeNumber(fields[key]) {
				return fmt.Errorf("%s must be zero or a positive number", strings.ReplaceAll(key, "_", " "))
			}
		}
	}
	for _, key := range []string{"estimated_hours", "capacity_hours", "citations", "downloads", "proposed_order"} {
		if fields[key] != "" && !nonNegativeNumber(fields[key]) {
			return fmt.Errorf("%s must be zero or a positive number", strings.ReplaceAll(key, "_", " "))
		}
	}
	for _, key := range []string{"citations", "downloads", "proposed_order"} {
		if fields[key] != "" {
			number, err := strconv.ParseFloat(fields[key], 64)
			if err != nil || number != float64(int64(number)) || (key == "proposed_order" && number < 1) {
				return fmt.Errorf("%s must be a whole number", strings.ReplaceAll(key, "_", " "))
			}
		}
	}
	if feature == "citation-manager" {
		id, err := strconv.ParseInt(fields["paper_id"], 10, 64)
		if err != nil || id <= 0 {
			return fmt.Errorf("choose a paper from your Literature Review Matrix")
		}
		if fields["accessed_date"] != "" && !validTrackingDate(fields["accessed_date"], false) {
			return fmt.Errorf("accessed date must be a valid date")
		}
	}
	if feature == "task-dependencies" {
		a, e1 := strconv.ParseInt(fields["task_id"], 10, 64)
		b, e2 := strconv.ParseInt(fields["depends_on_id"], 10, 64)
		if e1 != nil || e2 != nil || a <= 0 || b <= 0 || a == b {
			return fmt.Errorf("choose two different tasks")
		}
	}
	if feature == "team-workload" || feature == "authorship-agreement" {
		id, err := strconv.ParseInt(fields["member_id"], 10, 64)
		if err != nil || id <= 0 {
			return fmt.Errorf("choose a confirmed team member")
		}
	}
	if feature == "research-impact" && (fields["citations"] != "" || fields["downloads"] != "") {
		if strings.TrimSpace(fields["metric_source"]) == "" || strings.TrimSpace(fields["verified_date"]) == "" {
			return fmt.Errorf("add the metric source and verified date before saving citation or download counts")
		}
	}
	if feature == "project-export" {
		for _, key := range []string{"include_proposal", "include_literature", "include_code", "include_dataset_metadata", "include_experiments", "include_decisions"} {
			if fields[key] != "" && fields[key] != "true" && fields[key] != "false" {
				return fmt.Errorf("%s must be selected or cleared", strings.ReplaceAll(key, "_", " "))
			}
		}
	}
	if feature == "data-access-settings" && fields["embargo_start"] != "" && fields["embargo_end"] != "" && fields["embargo_start"] > fields["embargo_end"] {
		return fmt.Errorf("embargo end must be on or after the start date")
	}
	return nil
}

func validDOI(value string) bool {
	value = strings.TrimSpace(value)
	return strings.HasPrefix(strings.ToLower(value), "10.") && strings.Contains(value, "/") && !strings.ContainsAny(value, " \t\r\n")
}

func validResearchToolURL(value string) bool {
	u, err := url.ParseRequestURI(value)
	return err == nil && u.Host != "" && u.User == nil && (u.Scheme == "https" || u.Scheme == "http")
}

func nonNegativeNumber(value string) bool {
	n, err := strconv.ParseFloat(value, 64)
	return err == nil && n >= 0
}

func (a *App) researchQuestionParentIsAcyclic(projectID, editingID, parentID int64) bool {
	rows, err := a.db.Query(`SELECT id, fields_json FROM research_tool_records WHERE project_id=? AND feature_key='research-question-map'`, projectID)
	if err != nil {
		return false
	}
	defer rows.Close()
	parents := make(map[int64]int64)
	for rows.Next() {
		var id int64
		var raw string
		if rows.Scan(&id, &raw) != nil {
			return false
		}
		fields := map[string]string{}
		if json.Unmarshal([]byte(raw), &fields) != nil {
			return false
		}
		if id != editingID && fields["parent_question"] != "" {
			parent, parseErr := strconv.ParseInt(fields["parent_question"], 10, 64)
			if parseErr != nil {
				return false
			}
			parents[id] = parent
		}
	}
	if rows.Err() != nil {
		return false
	}
	seen := make(map[int64]bool)
	current := parentID
	for current > 0 {
		if current == editingID || seen[current] {
			return false
		}
		seen[current] = true
		current = parents[current]
	}
	return true
}

func (a *App) validateTaskDependencyGraph(projectID, editingID, taskID, dependsOnID int64) error {
	rows, err := a.db.Query(`SELECT id, fields_json FROM research_tool_records WHERE project_id=? AND feature_key='task-dependencies'`, projectID)
	if err != nil {
		return fmt.Errorf("could not validate task dependencies")
	}
	defer rows.Close()
	next := make(map[int64][]int64)
	for rows.Next() {
		var id int64
		var raw string
		if rows.Scan(&id, &raw) != nil {
			return fmt.Errorf("could not read existing task dependencies")
		}
		if id == editingID {
			continue
		}
		fields := map[string]string{}
		if json.Unmarshal([]byte(raw), &fields) != nil {
			return fmt.Errorf("an existing task dependency is invalid")
		}
		from, e1 := strconv.ParseInt(fields["task_id"], 10, 64)
		to, e2 := strconv.ParseInt(fields["depends_on_id"], 10, 64)
		if e1 != nil || e2 != nil || from <= 0 || to <= 0 {
			continue
		}
		if from == taskID && to == dependsOnID {
			return fmt.Errorf("this task dependency is already recorded")
		}
		next[from] = append(next[from], to)
	}
	if rows.Err() != nil {
		return fmt.Errorf("could not read existing task dependencies")
	}
	seen := make(map[int64]bool)
	stack := []int64{dependsOnID}
	for len(stack) > 0 {
		current := stack[len(stack)-1]
		stack = stack[:len(stack)-1]
		if current == taskID {
			return fmt.Errorf("this dependency would create a circular task sequence")
		}
		if seen[current] {
			continue
		}
		seen[current] = true
		stack = append(stack, next[current]...)
	}
	return nil
}

func (a *App) researchToolFieldExists(projectID int64, feature, field, value string, excludeID int64) (bool, error) {
	rows, err := a.db.Query(`SELECT id,fields_json FROM research_tool_records WHERE project_id=? AND feature_key=?`, projectID, feature)
	if err != nil {
		return false, err
	}
	defer rows.Close()
	for rows.Next() {
		var id int64
		var raw string
		if err := rows.Scan(&id, &raw); err != nil {
			return false, err
		}
		if id == excludeID {
			continue
		}
		fields := map[string]string{}
		if err := json.Unmarshal([]byte(raw), &fields); err != nil {
			return false, err
		}
		if fields[field] == value {
			return true, nil
		}
	}
	if err := rows.Err(); err != nil {
		return false, err
	}
	return false, nil
}

func (a *App) researchToolTitle(feature string, projectID int64, user User, fields map[string]string) (string, error) {
	switch feature {
	case "citation-manager":
		paperID, _ := strconv.ParseInt(fields["paper_id"], 10, 64)
		var title string
		err := a.db.QueryRow(`SELECT title FROM literature_papers WHERE id=? AND student_id IN (
			SELECT student_id FROM projects WHERE id=?
			UNION SELECT user_id FROM team_members WHERE project_id=?
		)`, paperID, projectID, projectID).Scan(&title)
		if err != nil {
			return "", fmt.Errorf("that paper is not available in your Literature Review Matrix")
		}
		return title, nil
	case "task-dependencies":
		taskID, _ := strconv.ParseInt(fields["task_id"], 10, 64)
		dependsID, _ := strconv.ParseInt(fields["depends_on_id"], 10, 64)
		var taskTitle, dependsTitle string
		if err := a.db.QueryRow("SELECT title FROM workspace_records WHERE id=? AND project_id=? AND kind IN ('task','milestone')", taskID, projectID).Scan(&taskTitle); err != nil {
			return "", fmt.Errorf("select a task or milestone from this project")
		}
		if err := a.db.QueryRow("SELECT title FROM workspace_records WHERE id=? AND project_id=? AND kind IN ('task','milestone')", dependsID, projectID).Scan(&dependsTitle); err != nil {
			return "", fmt.Errorf("select a prerequisite task or milestone from this project")
		}
		return taskTitle + " depends on " + dependsTitle, nil
	case "team-workload", "authorship-agreement":
		memberID, _ := strconv.ParseInt(fields["member_id"], 10, 64)
		var name string
		if err := a.db.QueryRow(`SELECT u.name FROM projects p JOIN users u ON u.id=? WHERE p.id=? AND (u.id=p.student_id OR EXISTS(SELECT 1 FROM team_members tm WHERE tm.project_id=p.id AND tm.user_id=u.id))`, memberID, projectID).Scan(&name); err != nil {
			return "", fmt.Errorf("choose a confirmed member of this project")
		}
		if feature == "team-workload" {
			return name + " · " + fields["reporting_period"], nil
		}
		return name + " · Author contribution", nil
	default:
		return strings.TrimSpace(fields["title"]), nil
	}
}

func (a *App) deleteResearchToolRecord(w http.ResponseWriter, r *http.Request, u User, feature string) {
	id, err := strconv.ParseInt(r.URL.Query().Get("id"), 10, 64)
	if err != nil || id <= 0 {
		fail(w, 400, "A valid record ID is required.")
		return
	}
	var projectID int64
	var foundFeature string
	if err := a.db.QueryRow("SELECT project_id, feature_key FROM research_tool_records WHERE id=?", id).Scan(&projectID, &foundFeature); err != nil || foundFeature != feature || !a.projectAccess(u, projectID) {
		fail(w, 404, "Research record not found.")
		return
	}
	if _, err := a.db.Exec("DELETE FROM research_tool_records WHERE id=? AND project_id=? AND feature_key=?", id, projectID, feature); err != nil {
		fail(w, 500, "Could not delete the research record.")
		return
	}
	reply(w, 200, map[string]string{"message": "Research record deleted."})
}

// The export route creates a real ZIP containing selected project metadata.
// It checks project access but does not treat Data Access policy records as
// enforced file-permission rules.
func (a *App) exportResearchProject(w http.ResponseWriter, r *http.Request) {
	u, err := a.user(r)
	if err != nil {
		fail(w, 401, "Please log in.")
		return
	}
	planID, err := strconv.ParseInt(r.URL.Query().Get("plan_id"), 10, 64)
	if err != nil || planID <= 0 {
		fail(w, 400, "Choose a saved export plan first.")
		return
	}
	var projectID int64
	var raw string
	if err := a.db.QueryRow("SELECT project_id, fields_json FROM research_tool_records WHERE id=? AND feature_key='project-export'", planID).Scan(&projectID, &raw); err != nil || !a.projectAccess(u, projectID) {
		fail(w, 404, "Export plan not found in a project you can access.")
		return
	}
	fields := map[string]string{}
	if json.Unmarshal([]byte(raw), &fields) != nil {
		fail(w, 500, "Export plan is invalid.")
		return
	}
	var project struct {
		ID        int64  `json:"id"`
		Title     string `json:"title"`
		Area      string `json:"area"`
		Abstract  string `json:"abstract"`
		Status    string `json:"status"`
		Feedback  string `json:"feedback"`
		StudentID int64  `json:"student_id"`
		TeacherID any    `json:"teacher_id"`
	}
	if err := a.db.QueryRow("SELECT id,title,area,abstract,status,feedback,student_id,teacher_id FROM projects WHERE id=?", projectID).Scan(&project.ID, &project.Title, &project.Area, &project.Abstract, &project.Status, &project.Feedback, &project.StudentID, &project.TeacherID); err != nil {
		fail(w, 500, "Could not load project information.")
		return
	}
	files := map[string]any{}
	binaryFiles := map[string][]byte{}
	codeFilesIncluded := 0
	codeFilesSkipped := 0
	var codeBytes int64
	if fields["include_code"] == "true" {
		// Read the file metadata first and close the result set before fetching
		// file contents. Keeping rows open while calling QueryRow on the same
		// SQLite DB can exhaust its single connection and deadlock the export.
		type exportSourceFile struct {
			id        int64
			name      string
			bucket    string
			objectKey string
			size      int64
		}
		codeExtensions := map[string]bool{
			".go": true, ".py": true, ".cpp": true, ".c": true,
			".js": true, ".ts": true, ".html": true, ".css": true,
			".java": true, ".sql": true, ".json": true, ".md": true,
		}
		var candidates []exportSourceFile
		var reservedBytes int64
		rows, queryErr := a.db.Query(`
			SELECT f.id, f.name, COALESCE(s.bucket,''), COALESCE(s.object_key,''),
			       COALESCE(s.byte_size, length(f.data))
			FROM workspace_files f
			LEFT JOIN workspace_storage s ON s.file_id=f.id
			WHERE f.project_id=? ORDER BY f.id
		`, projectID)
		if queryErr == nil {
			for rows.Next() {
				var file exportSourceFile
				if rows.Scan(&file.id, &file.name, &file.bucket, &file.objectKey, &file.size) != nil {
					codeFilesSkipped++
					continue
				}
				if !codeExtensions[strings.ToLower(filepath.Ext(file.name))] {
					continue
				}
				if file.size < 1 || file.size > 8<<20 || len(candidates) >= 20 || reservedBytes+file.size > 32<<20 {
					codeFilesSkipped++
					continue
				}
				candidates = append(candidates, file)
				reservedBytes += file.size
			}
			if rows.Err() != nil {
				codeFilesSkipped++
			}
			rows.Close()
		} else {
			codeFilesSkipped++
		}
		for _, file := range candidates {
			var data []byte
			var readErr error
			if file.bucket != "" && file.objectKey != "" {
				data, readErr = a.storageGet(r.Context(), file.bucket, file.objectKey, file.size)
			} else {
				readErr = a.db.QueryRow("SELECT data FROM workspace_files WHERE id=?", file.id).Scan(&data)
			}
			if readErr != nil || int64(len(data)) != file.size {
				codeFilesSkipped++
				continue
			}
			binaryFiles[fmt.Sprintf("code/%d-%s", file.id, filepath.Base(file.name))] = data
			codeFilesIncluded++
			codeBytes += file.size
		}
	}
	selection := map[string]bool{}
	for _, key := range []string{"include_proposal", "include_literature", "include_code", "include_dataset_metadata", "include_experiments", "include_decisions"} {
		selection[key] = fields[key] == "true"
	}
	files["manifest.json"] = map[string]any{
		"project_id":          projectID,
		"project_title":       project.Title,
		"generated_at":        time.Now().UTC().Format(time.RFC3339),
		"format":              "ResearchBridge ZIP metadata bundle",
		"selection":           selection,
		"code_included":       codeFilesIncluded > 0,
		"code_files_included": codeFilesIncluded,
		"code_files_skipped":  codeFilesSkipped,
		"note":                "Only selected metadata and source-code files uploaded to this project are included. Private binary datasets and other non-code files are not copied into this ZIP.",
	}
	files["handover-plan.json"] = map[string]any{"record_id": planID, "title": strings.TrimSpace(fields["title"]), "fields": fields}
	if fields["include_proposal"] == "true" {
		files["proposal.json"] = project
	}
	if fields["include_literature"] == "true" {
		papers, citations := a.exportProjectLiterature(projectID)
		files["literature.json"] = papers
		files["citation-details.json"] = citations
	}
	if fields["include_dataset_metadata"] == "true" {
		files["dataset-metadata.json"] = a.exportToolRows(projectID, "dataset-registry")
	}
	if fields["include_experiments"] == "true" {
		files["experiments.json"] = a.exportRows(`SELECT id,experiment_name,hypothesis,run_date,protocol,dataset_version,code_link,environment,parameters,random_seed,result_summary,artifact_link,notes FROM experiment_reproducibility_records WHERE project_id=? ORDER BY id`, projectID)
	}
	if fields["include_decisions"] == "true" {
		files["risk-and-decisions.json"] = a.exportToolRows(projectID, "risk-decision-log")
	}
	buf := new(bytes.Buffer)
	zw := zip.NewWriter(buf)
	for name, value := range files {
		entry, createErr := zw.Create(name)
		if createErr != nil {
			fail(w, 500, "Could not prepare project export.")
			return
		}
		encoded, marshalErr := json.MarshalIndent(value, "", "  ")
		if marshalErr != nil {
			fail(w, 500, "Could not prepare project export.")
			return
		}
		if _, writeErr := entry.Write(encoded); writeErr != nil {
			fail(w, 500, "Could not prepare project export.")
			return
		}
	}
	for name, data := range binaryFiles {
		entry, createErr := zw.Create(name)
		if createErr != nil {
			fail(w, 500, "Could not prepare source-code files.")
			return
		}
		if _, writeErr := entry.Write(data); writeErr != nil {
			fail(w, 500, "Could not prepare source-code files.")
			return
		}
	}
	if err := zw.Close(); err != nil {
		fail(w, 500, "Could not finish project export.")
		return
	}
	filename := fmt.Sprintf("researchbridge-project-%d.zip", projectID)
	w.Header().Set("Content-Type", "application/zip")
	w.Header().Set("Content-Disposition", `attachment; filename="`+filename+`"`)
	w.Header().Set("Content-Length", strconv.Itoa(buf.Len()))
	w.WriteHeader(200)
	_, _ = io.Copy(w, buf)
}

func (a *App) exportProjectLiterature(projectID int64) ([]map[string]any, []researchToolRecord) {
	citations := a.exportToolRows(projectID, "citation-manager")
	papers := make([]map[string]any, 0, len(citations))
	seen := make(map[int64]bool)
	for _, citation := range citations {
		paperID, err := strconv.ParseInt(citation.Fields["paper_id"], 10, 64)
		if err != nil || paperID <= 0 || seen[paperID] {
			continue
		}
		seen[paperID] = true
		rows := a.exportRows(`SELECT id,title,authors,publication_year,venue,doi,paper_url,objective,methodology,dataset,key_findings,limitations,research_gap,relevance FROM literature_papers WHERE id=? AND student_id IN (
			SELECT student_id FROM projects WHERE id=?
			UNION SELECT user_id FROM team_members WHERE project_id=?
		)`, paperID, projectID, projectID)
		if len(rows) > 0 && rows[0]["id"] != nil {
			papers = append(papers, rows[0])
		}
	}
	return papers, citations
}

func (a *App) exportRows(query string, args ...any) []map[string]any {
	rows, err := a.db.Query(query, args...)
	if err != nil {
		return []map[string]any{{"note": "This section was not available in the current database."}}
	}
	defer rows.Close()
	columns, err := rows.Columns()
	if err != nil {
		return []map[string]any{}
	}
	out := make([]map[string]any, 0)
	for rows.Next() {
		values := make([]any, len(columns))
		dest := make([]any, len(columns))
		for i := range values {
			dest[i] = &values[i]
		}
		if rows.Scan(dest...) != nil {
			continue
		}
		item := make(map[string]any, len(columns))
		for i, col := range columns {
			if b, ok := values[i].([]byte); ok {
				item[col] = string(b)
			} else {
				item[col] = values[i]
			}
		}
		out = append(out, item)
	}
	return out
}

func (a *App) exportToolRows(projectID int64, feature string) []researchToolRecord {
	rows, err := a.db.Query(`SELECT id,project_id,feature_key,title,fields_json,created_by,created_at,updated_at FROM research_tool_records WHERE project_id=? AND feature_key=? ORDER BY id`, projectID, feature)
	if err != nil {
		return []researchToolRecord{}
	}
	defer rows.Close()
	out := make([]researchToolRecord, 0)
	for rows.Next() {
		var item researchToolRecord
		var raw string
		if rows.Scan(&item.ID, &item.ProjectID, &item.Feature, &item.Title, &raw, &item.CreatedBy, &item.CreatedAt, &item.UpdatedAt) != nil {
			continue
		}
		item.Fields = map[string]string{}
		_ = json.Unmarshal([]byte(raw), &item.Fields)
		out = append(out, item)
	}
	return out
}
